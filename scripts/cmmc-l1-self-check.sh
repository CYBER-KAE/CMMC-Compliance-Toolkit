#!/usr/bin/env bash
# ==============================================================================
# CMMC Level 1 Self-Check Script
# By Petronella Technology Group (https://petronellatech.com)
#
# Checks basic CMMC Level 1 controls on a Linux/macOS system:
# - Access controls and user management
# - Authentication and password policy
# - System patching and updates
# - Antivirus/endpoint protection
# - Firewall status
# - Network boundary protection
# - Media sanitization tools
# - Physical access (informational only)
#
# Usage: ./cmmc-l1-self-check.sh [options]
#
# Options:
#   -o, --output FILE   Write report to FILE (default: stdout)
#   -v, --verbose       Show detailed check output
#   -h, --help          Show this help message
#
# This script does NOT modify any system settings. It is read-only.
# ==============================================================================

set -euo pipefail

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[0;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
BOLD='\033[1m'
NC='\033[0m'

PASS_COUNT=0
FAIL_COUNT=0
WARN_COUNT=0
INFO_COUNT=0
SKIP_COUNT=0

OUTPUT_FILE=""
VERBOSE=false

while [[ $# -gt 0 ]]; do
    case $1 in
        -o|--output)
            OUTPUT_FILE="$2"
            shift 2
            ;;
        -v|--verbose)
            VERBOSE=true
            shift
            ;;
        -h|--help)
            head -22 "$0" | tail -18
            exit 0
            ;;
        *)
            echo "Unknown option: $1"
            exit 1
            ;;
    esac
done

output() {
    if [[ -n "$OUTPUT_FILE" ]]; then
        echo -e "$@" | sed 's/\x1b\[[0-9;]*m//g' >> "$OUTPUT_FILE"
    fi
    echo -e "$@"
}

pass()    { output "  ${GREEN}[PASS]${NC} $1"; ((PASS_COUNT++)); }
fail()    { output "  ${RED}[FAIL]${NC} $1"; ((FAIL_COUNT++)); }
warn()    { output "  ${YELLOW}[WARN]${NC} $1"; ((WARN_COUNT++)); }
info()    { output "  ${BLUE}[INFO]${NC} $1"; ((INFO_COUNT++)); }
skip()    { output "  ${CYAN}[SKIP]${NC} $1"; ((SKIP_COUNT++)); }
detail()  { $VERBOSE && output "         $1" || true; }

if [[ -n "$OUTPUT_FILE" ]]; then
    > "$OUTPUT_FILE"
fi

output ""
output "${BOLD}============================================================================${NC}"
output "${BOLD}  CMMC Level 1 Self-Check Report${NC}"
output "${BOLD}  Generated by Petronella Technology Group${NC}"
output "${BOLD}  https://petronellatech.com${NC}"
output "${BOLD}============================================================================${NC}"
output ""
output "  Date:     $(date '+%Y-%m-%d %H:%M:%S %Z')"
output "  Hostname: $(hostname)"
output "  OS:       $(uname -s) $(uname -r)"
output "  User:     $(whoami)"
output ""
output "  ${BOLD}This script checks CMMC Level 1 (17 practices from FAR 52.204-21).${NC}"
output "  ${BOLD}Read-only -- no system changes are made.${NC}"
output ""

# ==============================================================================
# AC.L1-b.1.i -- Limit system access to authorized users
# ==============================================================================
output "${BOLD}--- AC.L1-b.1.i: Authorized Access Control ---${NC}"
output ""

# Check for unique user accounts
SYSTEM_USERS=$(awk -F: '$3 >= 1000 && $7 !~ /(nologin|false)/ {print $1}' /etc/passwd 2>/dev/null)
USER_COUNT=$(echo "$SYSTEM_USERS" | grep -c "." || echo "0")
info "Interactive user accounts found: $USER_COUNT"

# Check for duplicate UIDs
DUP_UIDS=$(awk -F: '{print $3}' /etc/passwd 2>/dev/null | sort | uniq -d)
if [[ -z "$DUP_UIDS" ]]; then
    pass "No duplicate UIDs found -- all accounts have unique identification"
else
    fail "Duplicate UIDs detected: $DUP_UIDS"
fi

# Check for accounts with empty shell or suspicious shells
NOLOGIN_COUNT=$(awk -F: '$7 ~ /(nologin|false)/ {count++} END {print count+0}' /etc/passwd 2>/dev/null)
info "System/service accounts with nologin shell: $NOLOGIN_COUNT"

# Check for inactive accounts (last login)
if command -v lastlog &>/dev/null; then
    NEVER_LOGGED=$(lastlog 2>/dev/null | awk '$NF == "in" || $0 ~ /Never logged/ {count++} END {print count+0}')
    if [[ "$NEVER_LOGGED" -gt 5 ]]; then
        warn "$NEVER_LOGGED accounts have never logged in -- review for unnecessary accounts"
    else
        info "Accounts that have never logged in: $NEVER_LOGGED"
    fi
fi

output ""

# ==============================================================================
# AC.L1-b.1.ii -- Limit access to authorized transactions/functions
# ==============================================================================
output "${BOLD}--- AC.L1-b.1.ii: Transaction and Function Control ---${NC}"
output ""

# Check sudo group membership
if getent group sudo &>/dev/null; then
    SUDO_MEMBERS=$(getent group sudo 2>/dev/null | awk -F: '{print $4}')
    SUDO_COUNT=$(echo "$SUDO_MEMBERS" | tr ',' '\n' | grep -c "." || echo "0")
    info "Users in sudo group: $SUDO_COUNT ($SUDO_MEMBERS)"
    if [[ "$SUDO_COUNT" -gt 5 ]]; then
        warn "Many users ($SUDO_COUNT) have sudo access -- review for least privilege"
    else
        pass "Sudo access limited to $SUDO_COUNT user(s)"
    fi
elif getent group wheel &>/dev/null; then
    WHEEL_MEMBERS=$(getent group wheel 2>/dev/null | awk -F: '{print $4}')
    WHEEL_COUNT=$(echo "$WHEEL_MEMBERS" | tr ',' '\n' | grep -c "." || echo "0")
    info "Users in wheel group: $WHEEL_COUNT ($WHEEL_MEMBERS)"
    if [[ "$WHEEL_COUNT" -gt 5 ]]; then
        warn "Many users ($WHEEL_COUNT) have wheel/admin access -- review for least privilege"
    else
        pass "Admin access limited to $WHEEL_COUNT user(s)"
    fi
fi

# Check world-writable directories
WORLD_WRITABLE=$(find /tmp /var/tmp -maxdepth 0 -perm -0002 -type d 2>/dev/null | wc -l || echo "0")
if [[ "$WORLD_WRITABLE" -gt 0 ]]; then
    # Check sticky bit
    STICKY=$(find /tmp /var/tmp -maxdepth 0 -perm -1000 -type d 2>/dev/null | wc -l || echo "0")
    if [[ "$STICKY" -ge "$WORLD_WRITABLE" ]]; then
        pass "World-writable directories have sticky bit set"
    else
        warn "World-writable directories without sticky bit may allow unauthorized modification"
    fi
fi

output ""

# ==============================================================================
# AC.L1-b.1.iii -- External system connections
# ==============================================================================
output "${BOLD}--- AC.L1-b.1.iii: External System Connections ---${NC}"
output ""

# Check for VPN clients
VPN_FOUND=false
for vpn in openvpn wireguard wg strongswan ipsec cisco openconnect; do
    if command -v "$vpn" &>/dev/null || pgrep -f "$vpn" &>/dev/null 2>&1; then
        pass "VPN client detected: $vpn"
        VPN_FOUND=true
        break
    fi
done

# Check WireGuard interface
if ip link show type wireguard 2>/dev/null | grep -q "wg"; then
    pass "WireGuard VPN interface active"
    VPN_FOUND=true
fi

if [[ "$VPN_FOUND" == false ]]; then
    info "No VPN client detected -- verify remote access controls if applicable"
fi

# Check for listening services (potential external exposure)
LISTENING=$(ss -tlnp 2>/dev/null | grep "LISTEN" | wc -l || echo "0")
info "Services listening on network ports: $LISTENING"
if $VERBOSE && [[ "$LISTENING" -gt 0 ]]; then
    ss -tlnp 2>/dev/null | grep "LISTEN" | while read -r line; do
        detail "$line"
    done
fi

output ""

# ==============================================================================
# IA.L1-b.1.v & IA.L1-b.1.vi -- Identification and Authentication
# ==============================================================================
output "${BOLD}--- IA.L1-b.1.v/vi: Identification and Authentication ---${NC}"
output ""

# Check password policy
if [[ -f /etc/security/pwquality.conf ]]; then
    pass "Password quality configuration exists"

    MIN_LEN=$(grep -i "^minlen" /etc/security/pwquality.conf 2>/dev/null | head -1 | awk -F= '{print $2}' | tr -d ' ')
    DCREDIT=$(grep -i "^dcredit" /etc/security/pwquality.conf 2>/dev/null | head -1 | awk -F= '{print $2}' | tr -d ' ')
    UCREDIT=$(grep -i "^ucredit" /etc/security/pwquality.conf 2>/dev/null | head -1 | awk -F= '{print $2}' | tr -d ' ')
    LCREDIT=$(grep -i "^lcredit" /etc/security/pwquality.conf 2>/dev/null | head -1 | awk -F= '{print $2}' | tr -d ' ')
    OCREDIT=$(grep -i "^ocredit" /etc/security/pwquality.conf 2>/dev/null | head -1 | awk -F= '{print $2}' | tr -d ' ')

    if [[ -n "$MIN_LEN" ]] && [[ "$MIN_LEN" -ge 8 ]]; then
        pass "Minimum password length: $MIN_LEN characters"
    elif [[ -n "$MIN_LEN" ]]; then
        fail "Minimum password length ($MIN_LEN) is below 8 characters"
    else
        warn "Minimum password length not explicitly set"
    fi
elif [[ -f /etc/pam.d/common-password ]]; then
    if grep -q "pam_pwquality\|pam_cracklib" /etc/pam.d/common-password 2>/dev/null; then
        pass "Password quality module configured in PAM"
    else
        warn "No password quality enforcement found in PAM"
    fi
else
    warn "No password quality configuration found"
fi

# Check for account lockout
LOCKOUT_FOUND=false
if grep -rq "pam_faillock" /etc/pam.d/ 2>/dev/null; then
    pass "Account lockout configured (pam_faillock)"
    LOCKOUT_FOUND=true
    if [[ -f /etc/security/faillock.conf ]]; then
        DENY=$(grep "^deny" /etc/security/faillock.conf 2>/dev/null | awk -F= '{print $2}' | tr -d ' ')
        UNLOCK=$(grep "^unlock_time" /etc/security/faillock.conf 2>/dev/null | awk -F= '{print $2}' | tr -d ' ')
        [[ -n "$DENY" ]] && info "Lockout after $DENY failed attempts"
        [[ -n "$UNLOCK" ]] && info "Unlock time: ${UNLOCK}s"
    fi
elif grep -rq "pam_tally2" /etc/pam.d/ 2>/dev/null; then
    pass "Account lockout configured (pam_tally2)"
    LOCKOUT_FOUND=true
fi

if [[ "$LOCKOUT_FOUND" == false ]]; then
    fail "No account lockout mechanism detected"
fi

# Check for MFA indicators
MFA_FOUND=false
if grep -rq "pam_google_authenticator\|pam_yubico\|pam_duo\|pam_u2f" /etc/pam.d/ 2>/dev/null; then
    pass "Multi-factor authentication module detected in PAM"
    MFA_FOUND=true
fi
if [[ "$MFA_FOUND" == false ]]; then
    info "No local MFA module detected (may be handled by directory service or SSO)"
fi

output ""

# ==============================================================================
# MP.L1-b.1.vii -- Media sanitization
# ==============================================================================
output "${BOLD}--- MP.L1-b.1.vii: Media Sanitization ---${NC}"
output ""

SANITIZE_TOOLS=0
for tool in shred wipe scrub nwipe secure-delete srm; do
    if command -v "$tool" &>/dev/null; then
        pass "Media sanitization tool available: $tool"
        ((SANITIZE_TOOLS++))
    fi
done

if [[ "$SANITIZE_TOOLS" -eq 0 ]]; then
    # shred is usually part of coreutils
    if command -v shred &>/dev/null; then
        pass "shred (coreutils) is available for media sanitization"
    else
        warn "No media sanitization tools detected -- install shred, wipe, or nwipe"
    fi
fi

output ""

# ==============================================================================
# SC.L1-b.1.xii -- Boundary protection (firewall)
# ==============================================================================
output "${BOLD}--- SC.L1-b.1.xii: Boundary Protection ---${NC}"
output ""

FIREWALL_ACTIVE=false

if [[ "$(uname -s)" == "Linux" ]]; then
    # nftables
    if command -v nft &>/dev/null; then
        NFT_RULES=$(nft list ruleset 2>/dev/null | wc -l || echo "0")
        if [[ "$NFT_RULES" -gt 2 ]]; then
            pass "nftables firewall active ($NFT_RULES rule lines)"
            FIREWALL_ACTIVE=true
        fi
    fi

    # iptables
    if [[ "$FIREWALL_ACTIVE" == false ]] && command -v iptables &>/dev/null; then
        IPT_INPUT=$(iptables -L INPUT -n 2>/dev/null | tail -n+3 | wc -l || echo "0")
        if [[ "$IPT_INPUT" -gt 0 ]]; then
            pass "iptables firewall has $IPT_INPUT INPUT rules"
            FIREWALL_ACTIVE=true

            # Check default policy
            DEFAULT_POLICY=$(iptables -L INPUT -n 2>/dev/null | head -1 | grep -o "policy [A-Z]*" | awk '{print $2}')
            if [[ "$DEFAULT_POLICY" == "DROP" ]] || [[ "$DEFAULT_POLICY" == "REJECT" ]]; then
                pass "Default INPUT policy is $DEFAULT_POLICY (deny by default)"
            elif [[ "$DEFAULT_POLICY" == "ACCEPT" ]]; then
                warn "Default INPUT policy is ACCEPT -- consider changing to DROP"
            fi
        fi
    fi

    # UFW
    if [[ "$FIREWALL_ACTIVE" == false ]] && command -v ufw &>/dev/null; then
        if ufw status 2>/dev/null | grep -q "Status: active"; then
            pass "UFW firewall is active"
            FIREWALL_ACTIVE=true
        fi
    fi

    # firewalld
    if [[ "$FIREWALL_ACTIVE" == false ]] && command -v firewall-cmd &>/dev/null; then
        if firewall-cmd --state 2>/dev/null | grep -q "running"; then
            pass "firewalld is running"
            FIREWALL_ACTIVE=true
            ZONE=$(firewall-cmd --get-default-zone 2>/dev/null || echo "unknown")
            info "Default zone: $ZONE"
        fi
    fi
fi

if [[ "$FIREWALL_ACTIVE" == false ]]; then
    fail "No active host firewall detected"
fi

output ""

# ==============================================================================
# SC.L1-b.1.xiii -- Public-facing subnetwork separation
# ==============================================================================
output "${BOLD}--- SC.L1-b.1.xiii: Subnetwork Separation ---${NC}"
output ""

# Check network interfaces
IFACE_COUNT=$(ip -o link show 2>/dev/null | grep -cv "lo:\|docker\|br-\|veth" || echo "0")
info "Network interfaces (excluding loopback/Docker): $IFACE_COUNT"

# Check for Docker/container networks (potential isolation)
if command -v docker &>/dev/null; then
    DOCKER_NETS=$(docker network ls --format '{{.Name}}' 2>/dev/null | wc -l || echo "0")
    if [[ "$DOCKER_NETS" -gt 0 ]]; then
        info "Docker networks found: $DOCKER_NETS (verify isolation of public-facing services)"
    fi
fi

info "Network segmentation requires architectural review -- verify DMZ separation manually"

output ""

# ==============================================================================
# SI.L1-b.1.xiv -- Flaw remediation (patching)
# ==============================================================================
output "${BOLD}--- SI.L1-b.1.xiv: Flaw Remediation (Patching) ---${NC}"
output ""

if [[ "$(uname -s)" == "Linux" ]]; then
    if command -v apt &>/dev/null; then
        apt update -qq 2>/dev/null || true
        SECURITY_UPDATES=$(apt list --upgradable 2>/dev/null | grep -ic "security" || echo "0")
        TOTAL_UPDATES=$(apt list --upgradable 2>/dev/null | grep -c "upgradable" || echo "0")
        info "Available updates: $TOTAL_UPDATES total, $SECURITY_UPDATES security"
        if [[ "$SECURITY_UPDATES" -gt 0 ]]; then
            fail "Security updates available ($SECURITY_UPDATES) -- apply promptly"
        elif [[ "$TOTAL_UPDATES" -eq 0 ]]; then
            pass "System is fully updated"
        else
            pass "No security updates pending (non-security updates available: $TOTAL_UPDATES)"
        fi
    elif command -v dnf &>/dev/null; then
        SEC_COUNT=$(dnf updateinfo list --security 2>/dev/null | grep -c "^" || echo "unknown")
        info "Security advisories pending: $SEC_COUNT"
    elif command -v pacman &>/dev/null; then
        UPDATES=$(pacman -Qu 2>/dev/null | wc -l || echo "0")
        info "Pending updates: $UPDATES"
        if [[ "$UPDATES" -eq 0 ]]; then
            pass "System is fully updated"
        elif [[ "$UPDATES" -gt 20 ]]; then
            warn "Many pending updates ($UPDATES) -- review and apply"
        fi
    elif command -v nix &>/dev/null; then
        info "NixOS detected -- updates managed declaratively"
        pass "NixOS systems are updated atomically via flake/channel"
    fi

    # Check auto-update services
    if systemctl is-enabled --quiet unattended-upgrades 2>/dev/null; then
        pass "Automatic security updates enabled (unattended-upgrades)"
    elif systemctl is-enabled --quiet dnf-automatic 2>/dev/null; then
        pass "Automatic updates enabled (dnf-automatic)"
    else
        info "No automatic update service detected"
    fi
fi

output ""

# ==============================================================================
# SI.L1-b.1.xv/xvi/xvii -- Malicious code protection
# ==============================================================================
output "${BOLD}--- SI.L1-b.1.xv-xvii: Malicious Code Protection ---${NC}"
output ""

AV_DETECTED=false

declare -A AV_CHECKS=(
    ["CrowdStrike Falcon"]="falcon-sensor"
    ["Carbon Black"]="cbagentd"
    ["SentinelOne"]="sentinelone"
    ["Microsoft Defender"]="mdatp"
    ["ESET"]="esets_daemon"
    ["Sophos"]="sophosd"
    ["Trend Micro"]="ds_agent"
    ["Cylance"]="cylancesvc"
)

for av_name in "${!AV_CHECKS[@]}"; do
    if pgrep -f "${AV_CHECKS[$av_name]}" &>/dev/null 2>&1; then
        pass "$av_name agent is running"
        AV_DETECTED=true
    fi
done

# Check directories for EDR agents
for dir in /opt/CrowdStrike /opt/carbonblack /opt/SentinelOne /opt/microsoft/mdatp /opt/sophos /opt/eset; do
    if [[ -d "$dir" ]]; then
        dirname=$(basename "$dir")
        pass "EDR/AV installation detected: $dir"
        AV_DETECTED=true
    fi
done

# ClamAV
if command -v clamscan &>/dev/null; then
    pass "ClamAV is installed"
    AV_DETECTED=true
    if pgrep -x clamd &>/dev/null || systemctl is-active --quiet clamav-daemon 2>/dev/null; then
        pass "ClamAV daemon is running (real-time protection)"
    else
        warn "ClamAV installed but daemon not running -- only on-demand scanning available"
    fi

    # Check signature freshness
    if command -v freshclam &>/dev/null; then
        if [[ -f /var/lib/clamav/daily.cvd ]] || [[ -f /var/lib/clamav/daily.cld ]]; then
            SIG_AGE=""
            for sigfile in /var/lib/clamav/daily.cvd /var/lib/clamav/daily.cld; do
                if [[ -f "$sigfile" ]]; then
                    SIG_DATE=$(stat -c %Y "$sigfile" 2>/dev/null || stat -f %m "$sigfile" 2>/dev/null || echo "0")
                    NOW=$(date +%s)
                    SIG_AGE=$(( (NOW - SIG_DATE) / 86400 ))
                    break
                fi
            done
            if [[ -n "$SIG_AGE" ]] && [[ "$SIG_AGE" -le 7 ]]; then
                pass "ClamAV signatures updated within last $SIG_AGE day(s)"
            elif [[ -n "$SIG_AGE" ]]; then
                warn "ClamAV signatures are $SIG_AGE days old -- update immediately"
            fi
        fi
    fi
fi

if [[ "$AV_DETECTED" == false ]]; then
    fail "No antivirus/endpoint protection detected on this system"
fi

output ""

# ==============================================================================
# PE Practices -- Physical Protection (informational)
# ==============================================================================
output "${BOLD}--- PE.L1-b.1.viii-xi: Physical Protection (Manual Checks) ---${NC}"
output ""
info "Physical access controls cannot be verified remotely. Verify manually:"
info "  - Facility access restricted to authorized personnel (PE.L1-b.1.viii)"
info "  - Visitors escorted and monitored (PE.L1-b.1.ix)"
info "  - Physical access logs maintained (PE.L1-b.1.x)"
info "  - Physical access devices (keys/badges) managed (PE.L1-b.1.xi)"
output ""

# ==============================================================================
# AC.L1-b.1.iv -- Public information control (informational)
# ==============================================================================
output "${BOLD}--- AC.L1-b.1.iv: Public Information Control (Manual Check) ---${NC}"
output ""
info "Public information posting controls cannot be fully verified by script."
info "  - Verify review/approval process for public-facing content"
info "  - Verify FCI is never posted to public systems"
output ""

# ==============================================================================
# Summary
# ==============================================================================
output "${BOLD}============================================================================${NC}"
output "${BOLD}  CMMC LEVEL 1 SELF-CHECK SUMMARY${NC}"
output "${BOLD}============================================================================${NC}"
output ""
output "  ${GREEN}PASS:${NC}    $PASS_COUNT"
output "  ${RED}FAIL:${NC}    $FAIL_COUNT"
output "  ${YELLOW}WARN:${NC}    $WARN_COUNT"
output "  ${BLUE}INFO:${NC}    $INFO_COUNT"
output "  ${CYAN}SKIP:${NC}    $SKIP_COUNT"
output ""

TOTAL_CHECKS=$((PASS_COUNT + FAIL_COUNT + WARN_COUNT))
if [[ "$TOTAL_CHECKS" -gt 0 ]]; then
    SCORE=$((PASS_COUNT * 100 / TOTAL_CHECKS))
    output "  Technical Controls Score: ${BOLD}${SCORE}%${NC} ($PASS_COUNT/$TOTAL_CHECKS passed)"
fi

output ""
output "  ${BOLD}Practices that require manual verification:${NC}"
output "    - AC.L1-b.1.iv  (Public information control)"
output "    - PE.L1-b.1.viii (Limit physical access)"
output "    - PE.L1-b.1.ix   (Escort visitors)"
output "    - PE.L1-b.1.x    (Physical access logs)"
output "    - PE.L1-b.1.xi   (Physical access devices)"
output ""

if [[ "$FAIL_COUNT" -gt 0 ]]; then
    output "  ${RED}${BOLD}$FAIL_COUNT FINDING(S) REQUIRE REMEDIATION${NC} before your CMMC Level 1 assessment."
fi
if [[ "$WARN_COUNT" -gt 0 ]]; then
    output "  ${YELLOW}${BOLD}$WARN_COUNT WARNING(S)${NC} should be reviewed and addressed."
fi

output ""
output "  ${BOLD}DISCLAIMER:${NC} This script checks a subset of technical controls only."
output "  CMMC Level 1 self-assessment requires evaluation of all 17 practices"
output "  including administrative and physical controls."
output ""
output "  ${BOLD}Need help with CMMC compliance?${NC}"
output "  Contact Petronella Technology Group: https://petronellatech.com/contact/"
output "  Phone: 919-348-4912"
output ""

if [[ -n "$OUTPUT_FILE" ]]; then
    echo ""
    echo "Report saved to: $OUTPUT_FILE"
fi
